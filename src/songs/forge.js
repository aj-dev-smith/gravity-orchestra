/* FORGE OF THE MARBLE KING — an original thrash-metal instrumental, written for the
   RIFF FORGE (the drop-forge electric guitar) and the machines that came up with it the
   same night: the BELLOWS HORNS, the LIGHT ORGAN, the string bass and the marble drum
   machine. The belt marble plays the LEAD GUITAR — long notes over the gallop are its
   tallest arcs, the harmony runs are its skims. Original composition (AJ / Cascade).

   KEY: E minor, with the metal's two favourite spices: F natural (the Phrygian ♭2 — the
   chromatic G·F#·F that drags every phrase back down to E) and A# (the tritone, diabolus
   in musica, in the riff's descending answer). B MAJOR (the D#) is the dominant — the
   brass and the organ get the harmonic-minor V that the guitar's power chords leave open.
   4/4. Written at a 110.5 quarter with 16ths = the 221 bpm cut-time thrash feel: every
   gallop is 8th + two 16ths, the "skank" double kick runs 16ths (.136 s apart).

   TEMPO / THE SEAM: bpm = 60·7/3.8 ≈ 110.53 (Canon's tempo), so the loop's fixed 3.8 s
   breath is EXACTLY 7 beats. The melody is 121 beats; + 7 = 128 = 32 bars, ~69.5 s.
   Nothing may strike inside the breath, so the song is BUILT around it: the last bar
   that plays is the ANVIL — at beat 120 the whole band hits a ringing B MAJOR (guitar B
   chord, horns, organ + choir, crash, bass) and lets it ring two bars, the dominant
   hanging over the void until the main riff slams back in on E, on the downbeat. V → i
   across the seam: the end of the loop is the reason the start of the loop exists.

   FORM (beats · bars):
     §1   0–16  1–4    THE MAIN RIFF. The forge alone with bass + drums: an E gallop
                       under the palm (E2:m chugs, 8th–16th–16th), the E5 ringing on
                       each downbeat, answered by G5–F#5 and then the descending
                       chromatic A#5·A5·G5·F#5 (the tritone). Bar 4 turns it upward
                       (G A A# B) into… The belt shadows the riff's accents two octaves
                       up: tall arcs on the E's, skims on the chromatic answers.
     §2  16–32  5–8    THE HOOK. The riff swaps its G–F# for C5 → B5 (♭VI → V) and the
                       BELLOWS HORNS hit the minor brass hook: Em stab · Em stab · C held
                       · B stab (four marbles slam four bellows); the belt sings the lead
                       melody over it (G5 F#5 E5 D#5 …). Bar 8 lands on a held B.
     §3  32–48  9–12   THE CHROMATIC WALK. A power chord on every beat, each followed by
                       its own two-16th chug (the gallop, but every beat a new chord):
                       E F F# G | A# A G F# | E F F# G | A A# B C. The belt moves AGAINST
                       it (B A# A G as the roots climb — contrary chromatics), then in
                       parallel 10ths (Maiden), octave-leaping eighths, and the climb to
                       E6. The double kick runs 16ths straight through. The horns stab
                       the final C.
     §4  48–64 13–16   THE BREAKDOWN. Half time: the snare only on 3, the chugs go
                       syncopated (rests are the riff), the E5 rings a whole beat, the F5 and
                       A#5 open on the off-beats, crashes on every one. The horns are a huge
                       held Em on each bar line. The belt throws the TALLEST arcs in the
                       piece — whole-bar E5 / G5 notes (apex ∝ dt²) — and bar 16 is the
                       chromatic G·F#·F tumbling down the toms into…
     §5  64–96 17–24   THE LIGHT ORGAN BRIDGE. C | B | Em | Em | Am | C | B | B. The organ
                       loft breathes held chords (Em and the final B held two bars each —
                       the slowest bellows in the room); the forge rings anthem power chords
                       (hit, and the "and" of 2). Bar 21 the CHOIR joins an octave up, the
                       horns swell, and the forge goes to TREMOLO PICKING: 16ths on single
                       notes, the belt's own melody an octave down (a twin lead, E5·C5·A4 |
                       G4·A4·G4·E4). Bars 23–24 the gallop comes back on B and builds — a 16th
                       chug run, a snare roll, the horns stabbing 8ths on B — into…
     §6  96–112 25–28  THE RETURN. The hook again, everyone (bar 28 = bar 4's climb).
     §7 112–128 29–32  THE ANVIL. Stop-time: C · C · C · B (horns + crash + kick in
                       unison), a 16th B chug run under a tom cascade (high → floor), the
                       belt's run up B Phrygian-dominant (B C D# E F# G A, A# the
                       leading note back to B) — and B major, rung through the 7-beat
                       breath, back to E.

   WHO LIVES WHERE:
     riff forge   E2–E5  power chords root–5th–octave (E5 = E2 B2 E3 …), palm-muted root
                         chugs ('E2:m'), the B-major anvil (B2 F#3 B3 D#4 F#4), the
                         tremolo line E4–E5. Same-string re-strike never under .136 s (the
                         16th) — the comfortable .13 s; the beam search fingers the rest.
     string bass  E2–C3  8 strings = the 8 roots (E F F# G A A# B C — the walk was written
                         to fit them: no G#, no D anywhere), doubling the riff at the
                         guitar's own octave on the 8th grid (the 16th chugs are the
                         guitar's alone: one string can't honestly repeat at .136 s).
     horns        A2–E4  11 horns: Em (E3 G3 B3 E4), C (C3 G3 C4 E4), B (B2 F#3 B3 D#4),
                         Am (A2 E3 A3 C4). Stabs = durBeats ≤ .5 (the slammed lid + the
                         stab voice), holds ≤ 4.5 beats (2.44 s, under the 2.6 s cap).
     organ        A2–G5  20 pipes. Bridge chords five deep; the choir an octave up from
                         bar 21 (its own pipes — a pipe can't speak two timbres at once).
     lead (belt)  B4–E6  the lead guitar.
   Drums: kick (the double kick — always in unison with the riff's rhythm, or 16ths
   straight), snare (2 & 4; 3 in the half-time), hat / ride (time), crash (accents — the
   kit's crash is the china too), the toms for the two chromatic tumbles.

   CLASHES THAT ARE MEANT: the tritone A#5 under E (§1), the F5 ♭2 against the belt's
   held E5 in the breakdown (one off-beat 8th), the C5 passing over the B pedal in the
   final run (Phrygian dominant). Everything else is consonant with its bar's chord.

   MIX: the forge is the star and plays at full level; the horns and organ sit a step
   under it (they're thick — five organ pipes at once), the bass doubles quietly enough
   that the guitar's roots read as one instrument. The belt reads on top.

   DIRECTOR: the forge's weight leads (it's the show), the sparse machines get help
   (the organ only plays the bridge + the anvil, the horns are stabs). Scripted cuts: the
   forge for the opening riff, the horns on the hook's entrance, the forge again for the
   walk, the belt's climb, the drum machine for the breakdown's half-time, the organ loft
   for the bridge, the forge's tremolo, the horns' build, the forge for the return, the
   horns on the stop-time, the toms' cascade — and THE ANVIL on the forge: a cut half a beat
   before the B-major hit, held through the breath (a script past the last note owns the seam;
   the stage wide cropped the forge at the front corner) and on into the main riff — V → i on
   one machine, one shot.

   iOS NOTE (§5): the sample path ignores `dur` and volume — the horns' stabs have their
   own baked voice (stab:<note>) so they stay short anyway; the organ's held chords ring
   their full render. Drum velocity (the crescendo runs) lives on the webaudio path only.
   ============================================================ */

// ---- helpers -----------------------------------------------------------------------
const r5 = x => +x.toFixed(5);
const v3 = x => +x.toFixed(3);
const sum = line => line.reduce((s, [, d]) => s + d, 0);
const sortHits = hs => hs.sort((a, b) => (Array.isArray(a) ? a[0] : a) - (Array.isArray(b) ? b[0] : b));

// ---- the forge's chord shapes -------------------------------------------------------
// power chords, root–5th–octave on the low strings; the root's lowest note is the chug
const P5 = {
  E: ['E2', 'B2', 'E3'], F: ['F2', 'C3', 'F3'], 'F#': ['F#2', 'C#3', 'F#3'], G: ['G2', 'D3', 'G3'],
  A: ['A2', 'E3', 'A3'], 'A#': ['A#2', 'F3', 'A#3'], B: ['B2', 'F#3', 'B3'], C: ['C3', 'G3', 'C4'],
};
const ROOT = { E: 'E2', F: 'F2', 'F#': 'F#2', G: 'G2', A: 'A2', 'A#': 'A#2', B: 'B2', C: 'C3' };   // = the bass's 8 strings

/* A bar of riff, as data: [offset, kind, root, vel?, dur?]. kind 'C' = an open power chord
   (dur > .3 beats → it rings), 'm' = a palm-muted chug on the root. */
const C = (o, r, v = .95, d = .5) => [o, 'C', r, v, d];
const m = (o, r = 'E', v = .68) => [o, 'm', r, v];
const GALLOP = [m(.5, 'E', .6), m(.75), m(1, 'E', .74), m(1.5, 'E', .66), m(1.75)];   // under the E5 on the one

const R1 = [C(0, 'E', 1), ...GALLOP, C(2, 'G'), C(2.5, 'F#', .9), m(3, 'E', .72), m(3.5, 'E', .64), m(3.75)];
const R2 = [C(0, 'E', 1), ...GALLOP, C(2, 'A#'), C(2.5, 'A', .9), C(3, 'G', .92), C(3.5, 'F#', .88)];
const R4 = [C(0, 'E', 1), ...GALLOP, C(2, 'G', .86), C(2.5, 'A', .9), C(3, 'A#', .94), C(3.5, 'B', 1)];   // the climb
const H1 = [C(0, 'E', 1), ...GALLOP, C(2, 'C', 1, 1), C(3, 'B', .95), m(3.5, 'B', .66), m(3.75, 'B', .62)];
const H4 = [C(0, 'E', 1), ...GALLOP, C(2, 'C', .95), m(2.5, 'C', .66), m(2.75, 'C', .62), C(3, 'B', 1, 1)];
const walk = roots => roots.flatMap((r, i) => [C(i, r, i ? .9 : 1), m(i + .5, r, .64), m(i + .75, r, .6)]);
const BD1 = [C(0, 'E', 1, 1), m(1.5, 'E', .8), m(1.75, 'E', .7), m(2, 'E', .86), m(2.75, 'E', .72), m(3.25, 'E', .76), C(3.5, 'F', .95)];
const BD2 = [C(0, 'E', 1, 1), m(1.5, 'E', .8), m(1.75, 'E', .7), m(2.5, 'E', .8), m(2.75, 'E', .72), C(3, 'A#', 1, 1)];
const BD4 = [C(0, 'E', 1, 1), m(1, 'E', .8), m(1.5, 'E', .78), C(2, 'G', .95), C(2.5, 'F#', .92), C(3, 'F', .95), m(3.5, 'E', .7), m(3.75, 'E', .76)];
const anthem = r => [C(0, r, 1, 1.5), C(1.5, r, .86, 2.5)];
const gallopOn = (r, v = .9) => [C(0, r, v), ...GALLOP.map(([o, k, , vv]) => [o, k, r, vv]), C(2, r, v * .95),
                                 m(2.5, r, .64), m(2.75, r), m(3, r, .74), m(3.5, r, .66), m(3.75, r)];
const run16 = (r, v0, v1) => Array.from({ length: 16 }, (_, i) => m(i / 4, r, v3(v0 + (v1 - v0) * i / 15)));

// the chart: one entry per bar, in order (32 bars = 128 beats; bars 31–32 are the anvil + the breath)
const CHART = [
  R1, R2, R1, R4,                                                             // §1   0
  H1, R2, H1, H4,                                                             // §2  16
  walk(['E', 'F', 'F#', 'G']), walk(['A#', 'A', 'G', 'F#']),                  // §3  32
  walk(['E', 'F', 'F#', 'G']), walk(['A', 'A#', 'B', 'C']),
  BD1, BD2, BD1, BD4,                                                         // §4  48
  anthem('C'), anthem('B'), anthem('E'), anthem('E'),                         // §5  64
  null, null,                                                                 //     80  (the tremolo — below)
  gallopOn('B', .9), [C(0, 'B', 1), ...run16('B', .55, .98).slice(1)],        //     88
  H1, R2, H1, R4,                                                             // §6  96
  [C(0, 'C', 1, .75), C(.75, 'C', .95, .75), C(1.5, 'C', .97), C(2, 'B', 1, 2)],  // §7 112  stop-time
  run16('B', .5, 1),                                                          //    116  the chug run under the toms
];

// ---- the riff forge + the bass (both read off the chart) -----------------------------
const riff = [], bass = [];
CHART.forEach((bar, i) => {
  if (!bar) return;
  const b0 = 4 * i;
  for (const [o, k, r, v, d] of bar){
    const b = r5(b0 + o);
    if (k === 'C') for (const n of P5[r]) riff.push([b, n, v, d]);
    else riff.push([b, ROOT[r] + ':m', v]);
    if (Math.abs(o * 2 - Math.round(o * 2)) < 1e-9) bass.push([b, ROOT[r], v3(Math.min(1, v * (k === 'C' ? .9 : .8)))]);   // the 8th grid only
  }
});
// §5 bars 21–22 — TREMOLO: the belt's line an octave down in 16ths, an A5 / C5 power chord
// under each bar's first stroke (the bass holds the roots)
const TREM = [['E5', 2], ['C5', 1], ['A4', 1], ['G4', 1.5], ['A4', .5], ['G4', 1], ['E4', 1]];
{
  let b = 80;
  for (const [n, d] of TREM){
    for (let k = 0; k < d * 4; k++) riff.push([r5(b + k / 4), n, v3(k % 4 ? .62 : .8), .32]);   // > .3 = open, not a chug; .4 bled the last E4 into bar 23's B
    b += d;
  }
  for (const n of P5.A) riff.push([80, n, .95, 2]);
  for (const n of P5.C) riff.push([84, n, .95, 2]);
  bass.push([80, 'A2', .85], [81, 'A2', .7], [82, 'A2', .75], [83, 'A2', .7],
            [84, 'C3', .85], [85, 'C3', .7], [86, 'C3', .75], [87, 'C3', .7]);
}
// §7 the ANVIL: a ringing B major — the forge's whole hand (it rings through the breath)
for (const n of ['B2', 'F#3', 'B3', 'D#4', 'F#4']) riff.push([120, n, 1, 8]);
bass.push([120, 'B2', 1]);
sortHits(riff); sortHits(bass);

// ---- THE LEAD (belt) — the lead guitar ------------------------------------------------
const melody = [
  // §1 the riff's shadow, two octaves up (tall E's, chromatic skims)
  ['E5', 2], ['G5', .5], ['F#5', 1.5],
  ['E5', 2], ['A#5', .5], ['A5', .5], ['G5', .5], ['F#5', .5],
  ['E5', 2], ['G5', .5], ['F#5', 1.5],
  ['E5', 2], ['G5', .5], ['A5', .5], ['A#5', .5], ['B5', .5],
  // §2 the lead melody over the hook
  ['G5', 1.5], ['F#5', .5], ['E5', 1], ['D#5', 1],
  ['E5', 1.5], ['B4', .5], ['A#4', .5], ['A4', .5], ['G4', .5], ['F#4', .5],
  ['G5', 1.5], ['A5', .5], ['G5', 1], ['F#5', 1],
  ['E5', 1], ['G5', .5], ['B5', .5], ['C6', 1], ['B5', 1],
  // §3 against the walk: contrary chromatics, parallel 10ths, octave leaps, the climb to E6
  ['B5', 1], ['A#5', 1], ['A5', 1], ['G5', 1],
  ['D6', 1], ['C6', 1], ['B5', 1], ['A#5', 1],
  ['B5', .5], ['B4', .5], ['A#5', .5], ['A#4', .5], ['A5', .5], ['A4', .5], ['G5', .5], ['G4', .5],
  ['C6', 1], ['D6', 1], ['D#6', 1], ['E6', 1],
  // §4 the breakdown: the tallest arcs in the piece
  ['E5', 4],
  ['E5', 3], ['F5', 1],
  ['G5', 4],
  ['B4', 2], ['G5', .5], ['F#5', .5], ['F5', .5], ['E5', .5],
  // §5 the bridge — the lead sings
  ['G5', 3], ['E5', .5], ['G5', .5],
  ['F#5', 2], ['D#5', 1], ['F#5', 1],
  ['G5', 2], ['B5', 2],
  ['E6', 4],
  ['E6', 2], ['C6', 1], ['A5', 1],
  ['G5', 1.5], ['A5', .5], ['G5', 1], ['E5', 1],
  ['F#5', 2], ['D#5', 1], ['B4', 1],
  ['D#5', 3], ['F#5', 1],
  // §6 the return (bar 28 doubles the climb)
  ['G5', 1.5], ['F#5', .5], ['E5', 1], ['D#5', 1],
  ['E5', 1.5], ['B4', .5], ['A#4', .5], ['A4', .5], ['G4', .5], ['F#4', .5],
  ['G5', 1.5], ['A5', .5], ['G5', 1], ['F#5', 1],
  ['E5', 2], ['G5', .5], ['A5', .5], ['A#5', .5], ['B5', .5],
  // §7 stop-time, the Phrygian-dominant run, the anvil
  ['E5', .75], ['E5', .75], ['E5', .5], ['D#5', 2],
  ['B4', .5], ['C5', .5], ['D#5', .5], ['E5', .5], ['F#5', .5], ['G5', .5], ['A5', .5], ['A#5', .5],
  ['B5', 1],
];

// ---- BELLOWS HORNS -------------------------------------------------------------------
const HV = { Em: ['E3', 'G3', 'B3', 'E4'], C: ['C3', 'G3', 'C4', 'E4'], B: ['B2', 'F#3', 'B3', 'D#4'], Am: ['A2', 'E3', 'A3', 'C4'] };
const horns = [];
const hit = (b, ch, v, d = .5) => HV[ch].forEach((n, j) => horns.push([r5(b), n, v3(v * (1 - .06 * j)), d]));   // top voices a hair under the bass of the chord
const hook = (b, last) => {          // the hook bar: Em stab · Em stab · C held · B stab
  hit(b, 'Em', 1); hit(b + 1.5, 'Em', .86);
  if (last === 'climb'){ hit(b + 3.5, 'B', .9); return; }
  if (last === 'land'){ hit(b + 2, 'C', .9); hit(b + 3, 'B', 1, 1); return; }
  if (last === 'answer'){ hit(b + 3.5, 'B', .84); return; }
  hit(b + 2, 'C', .95, 1); hit(b + 3, 'B', .9);
};
for (const b0 of [16, 96]){
  hook(b0); hook(b0 + 4, 'answer'); hook(b0 + 8); hook(b0 + 12, b0 === 16 ? 'land' : 'climb');
}
hit(47, 'C', .9);                                                         // the walk's last step
for (const [b, v] of [[48, 1], [52, .9], [56, 1], [60, .92]]) hit(b, 'Em', v, 1.5);   // the breakdown's bar lines
hit(80, 'Am', .7, 4); hit(84, 'C', .74, 4); hit(88, 'B', .78, 4);         // the bridge swells
hit(92, 'B', .8, 2); [94, 94.5, 95, 95.5].forEach((b, i) => hit(b, 'B', .72 + .08 * i));
hit(112, 'C', 1); hit(112.75, 'C', .95); hit(113.5, 'C', .97); hit(114, 'B', 1, 2);   // stop-time
hit(120, 'B', 1, 4.5);                                                    // the anvil
sortHits(horns);

// ---- LIGHT ORGAN [beat, note(|timbre), vel, beats] -----------------------------------
const OV = { C: ['C3', 'G3', 'C4', 'E4', 'G4'], B: ['B2', 'F#3', 'B3', 'D#4', 'F#4'], Em: ['E3', 'B3', 'E4', 'G4', 'B4'], Am: ['A2', 'E3', 'A3', 'C4', 'E4'] };
const CHOIR = { Am: ['A4', 'C5', 'E5'], C: ['C5', 'E5', 'G5'], B: ['B4', 'D#5', 'F#5'] };
const organ = [];
const chord = (b, ch, v, d, choir = false) => {
  OV[ch].forEach((n, j) => organ.push([b, n, v3(v * (1 - .05 * j)), d]));
  if (choir) CHOIR[ch].forEach((n, j) => organ.push([b, n + '|choir', v3(v * .8 * (1 - .05 * j)), d]));
};
chord(64, 'C', .7, 4); chord(68, 'B', .72, 4); chord(72, 'Em', .78, 8);
chord(80, 'Am', .82, 4, true); chord(84, 'C', .85, 4, true); chord(88, 'B', .9, 8, true);
chord(120, 'B', .62, 7.6, true);                                          // the anvil, held through the breath
// (review: at full velocity the organ + choir ALONE in the breath measured −11 dB RMS — 4 dB
//  louder than the whole band in §1 (−15), so the main riff came back in UNDER the chord it
//  resolves. The hit at 120 is carried by the forge, horns, crash and bass; the organ is the
//  ring, and it now sits just under the riff it hands the loop back to.)
sortHits(organ);

// ---- DRUMS ---------------------------------------------------------------------------
const D = { kick: [], snare: [], hat: [], ride: [], crash: [], tomHigh: [], tomHiMid: [], tomMid: [], tomLow: [], floorHigh: [] };
const kickWith = (bar, b0, s = 1) => { for (const [o, k, , v] of bar) D.kick.push([r5(b0 + o), v3(Math.min(1, (k === 'C' ? .9 : .72) * s))]); };
const backbeat = (b0, v = .86) => D.snare.push([b0 + 1, v], [b0 + 3, v]);
{
  // §1 — the main riff: kick in unison with the riff, snare 2 & 4, hats in 8ths
  [R1, R2, R1, R4].forEach((bar, i) => {
    const b0 = 4 * i; kickWith(bar, b0); backbeat(b0);
    for (let k = 0; k < 8; k++) D.hat.push([b0 + k / 2, k % 2 ? .3 : .45]);
  });
  D.crash.push([0, 1]);                                       // the loop's arrival: V → i lands here
  // §2 / §6 — the hook: ride quarters, crash every two bars and on the C held
  for (const s0 of [16, 96]){
    const bars = s0 === 16 ? [H1, R2, H1, H4] : [H1, R2, H1, R4];
    bars.forEach((bar, i) => {
      const b0 = s0 + 4 * i; kickWith(bar, b0); backbeat(b0, .9);
      for (let k = 0; k < 4; k++) D.ride.push([b0 + k, k ? .45 : .55]);
    });
    D.crash.push([s0, 1], [s0 + 8, .9]);
  }
  // §3 — the walk: double kick 16ths straight through, snare 2 & 4, crash each bar, ride 8ths
  for (let b = 32; b < 48; b += .25) D.kick.push([r5(b), (b % 1) ? .66 : .82]);
  for (let b0 = 32; b0 < 48; b0 += 4){
    backbeat(b0, .92); D.crash.push([b0, b0 === 32 ? 1 : .78]);
    for (let k = 1; k < 8; k++) D.ride.push([b0 + k / 2, k % 2 ? .32 : .42]);
  }
  // §4 — the breakdown: half time (snare on 3), kick with the chugs, crashes on the opens
  [BD1, BD2, BD1, BD4].forEach((bar, i) => {
    const b0 = 48 + 4 * i; kickWith(bar, b0, 1.08);
    D.snare.push([b0 + 2, 1]); D.crash.push([b0, .95]);
    for (const [o, k] of bar) if (k === 'C' && o) { if (i < 3) D.crash.push([r5(b0 + o), .7]); }
  });
  D.tomHigh.push([62, .85]); D.tomMid.push([62.5, .88]); D.floorHigh.push([63, .95]);   // G · F# · F, down the toms
  // §5 — the bridge: half-time anthem (17–20), the tremolo's double kick (21–22), the B gallop (23–24)
  for (let b0 = 64; b0 < 80; b0 += 4){
    D.kick.push([b0, .92], [b0 + 1.5, .8], [b0 + 2.5, .62]); D.snare.push([b0 + 2, .92]);
    D.crash.push([b0, b0 === 64 ? 1 : .72]);
    for (let k = 1; k < 8; k++) D.ride.push([b0 + k / 2, k % 2 ? .3 : .4]);
  }
  for (let b = 80; b < 88; b += .25) D.kick.push([r5(b), (b % 1) ? .62 : .8]);
  for (const b0 of [80, 84]){ backbeat(b0, .9); D.crash.push([b0, .9]); for (let k = 1; k < 4; k++) D.ride.push([b0 + k, .45]); }
  kickWith(CHART[22], 88); backbeat(88, .9); D.crash.push([88, .9]);
  kickWith(CHART[23], 92); D.snare.push([93, .9]); D.crash.push([92, .8]);
  for (let k = 0; k < 8; k++) D.snare.push([r5(94 + k / 4), v3(.55 + .45 * k / 7)]);    // the roll into the return
  // §7 — stop-time, the tom cascade, the anvil
  for (const [b, v] of [[112, 1], [112.75, .92], [113.5, .95], [114, 1]]){ D.kick.push([b, v]); D.crash.push([b, v * (b === 114 || b === 112 ? 1 : .7)]); }
  D.snare.push([112.75, .85], [113.5, .9]);
  const TOMS = ['tomHigh', 'tomHiMid', 'tomMid', 'tomLow', 'floorHigh'];
  for (let k = 0; k < 16; k++){
    const b = r5(116 + k / 4), lane = TOMS[Math.min(4, Math.floor(k / 3.2))];
    D[lane].push([b, v3(.6 + .4 * k / 15)]);
    if (k % 2 === 0) D.kick.push([b, v3(.7 + .3 * k / 15)]);
  }
  D.kick.push([120, 1]); D.snare.push([120, 1]); D.crash.push([120, 1]);
  for (const l of Object.keys(D)){
    // one strike per lane per instant (a crash on the riff's open and the bar line can't double)
    const seen = new Set();
    D[l] = sortHits(D[l]).filter(([b]) => !seen.has(b) && seen.add(b));
  }
}

